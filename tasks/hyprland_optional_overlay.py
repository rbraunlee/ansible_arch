#!/usr/bin/env python3
"""Safely render the fixed Ansible-owned Hyprland optional overlay.

The Ansible task deliberately supplies a fixed /home/<username> path.  This
helper traverses the controlled components through directory descriptors with
O_NOFOLLOW and replaces the leaf through its opened parent descriptor, so a
symlink cannot redirect this invocation outside the canonical destination.
"""

import argparse
import errno
import json
import os
from pathlib import PurePosixPath
import pwd
import secrets
import stat
import sys


MARKER = "-- ansible_arch_optional_overlay_v1"
OVERLAY_COMPONENTS = (".config", "ansible_arch", "hyprland-optional.lua")


class OverlayError(RuntimeError):
    """A safe overlay operation could not be completed."""


def parse_boolean(value):
    if value == "true":
        return True
    if value == "false":
        return False
    raise argparse.ArgumentTypeError("expected true or false")


def render_overlay(voxtype_enabled, nvidia_environment):
    return (
        f"{MARKER}\n"
        "-- Generated by ansible_arch from optional_profiles. Do not edit this file;\n"
        "-- use a complete host_vars optional_profiles mapping instead.\n"
        "return {\n"
        f"  voxtype_enabled = {'true' if voxtype_enabled else 'false'},\n"
        f"  nvidia_environment = {'true' if nvidia_environment else 'false'},\n"
        "}\n"
    ).encode("utf-8")


def open_directory(parent_fd, name, expected_uid, create, check_mode):
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    try:
        child_fd = os.open(name, flags, dir_fd=parent_fd)
    except FileNotFoundError:
        if check_mode:
            return None, True
        if not create:
            raise OverlayError(f"required directory {name!r} does not exist")
        try:
            os.mkdir(name, 0o755, dir_fd=parent_fd)
        except FileExistsError:
            pass
        child_fd = os.open(name, flags, dir_fd=parent_fd)
    except OSError as error:
        if error.errno in (errno.ELOOP, errno.ENOTDIR):
            raise OverlayError(f"controlled ancestor {name!r} must be a non-symlink directory") from error
        raise

    metadata = os.fstat(child_fd)
    if not stat.S_ISDIR(metadata.st_mode):
        os.close(child_fd)
        raise OverlayError(f"controlled ancestor {name!r} must be a directory")
    if expected_uid is not None and metadata.st_uid != expected_uid:
        os.close(child_fd)
        raise OverlayError(f"controlled ancestor {name!r} is not owned by the configured user")
    return child_fd, False


def open_canonical_home(home, username, expected_uid):
    requested = PurePosixPath(home)
    if not requested.is_absolute() or ".." in requested.parts:
        raise OverlayError("overlay home must be an absolute, normalized path")

    root_fd = os.open("/", os.O_RDONLY | os.O_DIRECTORY)
    current_fd = root_fd
    try:
        for component in requested.parts[1:]:
            next_fd, would_create = open_directory(
                current_fd,
                component,
                expected_uid if component == requested.parts[-1] else None,
                create=False,
                check_mode=False,
            )
            if would_create:
                raise OverlayError("overlay home must already exist")
            if component != requested.parts[-1]:
                # Parent ownership is not controlled by this profile; only
                # require a real directory so traversal cannot escape.
                metadata = os.fstat(next_fd)
                if not stat.S_ISDIR(metadata.st_mode):
                    os.close(next_fd)
                    raise OverlayError(f"ancestor {component!r} must be a directory")
            if current_fd != root_fd:
                os.close(current_fd)
            current_fd = next_fd
        return current_fd
    except Exception:
        if current_fd != root_fd:
            os.close(current_fd)
        raise
    finally:
        os.close(root_fd)


def read_existing(parent_fd, expected_uid):
    name = OVERLAY_COMPONENTS[-1]
    try:
        metadata = os.stat(name, dir_fd=parent_fd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(metadata.st_mode):
        raise OverlayError("optional overlay must be a regular non-symlink file")
    if metadata.st_uid != expected_uid:
        raise OverlayError("optional overlay is not owned by the configured user")
    try:
        descriptor = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=parent_fd)
    except OSError as error:
        if error.errno == errno.ELOOP:
            raise OverlayError("optional overlay must not be a symlink") from error
        raise
    try:
        opened_metadata = os.fstat(descriptor)
        if not stat.S_ISREG(opened_metadata.st_mode) or opened_metadata.st_uid != expected_uid:
            raise OverlayError("optional overlay changed while it was being inspected")
        return os.read(descriptor, 1024 * 1024)
    finally:
        os.close(descriptor)


def atomic_replace(parent_fd, payload):
    temporary_name = f".hyprland-optional-{os.getpid()}-{secrets.token_hex(16)}"
    descriptor = None
    try:
        descriptor = os.open(
            temporary_name,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
            0o644,
            dir_fd=parent_fd,
        )
        os.write(descriptor, payload)
        os.fsync(descriptor)
        os.close(descriptor)
        descriptor = None
        os.replace(
            temporary_name,
            OVERLAY_COMPONENTS[-1],
            src_dir_fd=parent_fd,
            dst_dir_fd=parent_fd,
        )
    except Exception:
        if descriptor is not None:
            os.close(descriptor)
        try:
            os.unlink(temporary_name, dir_fd=parent_fd)
        except FileNotFoundError:
            pass
        raise


def run(arguments):
    account = pwd.getpwnam(arguments.username)
    if os.geteuid() != account.pw_uid:
        raise OverlayError("overlay helper must run as the configured user")
    expected_home = PurePosixPath("/home", arguments.username)
    if (
        PurePosixPath(arguments.home) != expected_home
        and os.environ.get("ANSIBLE_ARCH_OPTIONAL_OVERLAY_TEST") != "1"
    ):
        raise OverlayError("overlay home must be the canonical configured-user home")

    payload = render_overlay(arguments.voxtype_enabled, arguments.nvidia_environment)
    home_fd = open_canonical_home(arguments.home, arguments.username, account.pw_uid)
    try:
        config_fd, config_would_change = open_directory(
            home_fd, OVERLAY_COMPONENTS[0], account.pw_uid, create=True, check_mode=arguments.check
        )
        if config_would_change:
            return {"changed": True, "path": str(PurePosixPath(arguments.home, *OVERLAY_COMPONENTS))}
        try:
            overlay_dir_fd, overlay_dir_would_change = open_directory(
                config_fd, OVERLAY_COMPONENTS[1], account.pw_uid, create=True, check_mode=arguments.check
            )
            if overlay_dir_would_change:
                return {"changed": True, "path": str(PurePosixPath(arguments.home, *OVERLAY_COMPONENTS))}
            try:
                existing = read_existing(overlay_dir_fd, account.pw_uid)
                if existing is not None and MARKER.encode("utf-8") not in existing:
                    raise OverlayError("refusing to replace an unowned optional overlay")
                changed = existing != payload
                if changed and not arguments.check:
                    atomic_replace(overlay_dir_fd, payload)
                return {"changed": changed, "path": str(PurePosixPath(arguments.home, *OVERLAY_COMPONENTS))}
            finally:
                os.close(overlay_dir_fd)
        finally:
            os.close(config_fd)
    finally:
        os.close(home_fd)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--home", required=True)
    parser.add_argument("--username", required=True)
    parser.add_argument("--voxtype-enabled", required=True, type=parse_boolean)
    parser.add_argument("--nvidia-environment", required=True, type=parse_boolean)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    arguments.check = arguments.check or os.environ.get("ANSIBLE_ARCH_OPTIONAL_OVERLAY_CHECK") == "1"
    try:
        print(json.dumps(run(arguments), sort_keys=True))
    except (KeyError, OSError, OverlayError) as error:
        print(f"hyprland optional overlay: {error}", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
